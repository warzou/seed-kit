python3 present
serve-readonly.py installed
index.html installed
port 54321 free
NetworkManager running
wlan0 present
no active Wifi-Kit recovery leftovers
wrapper installed if privileged actions enabled
'

WIFI_KIT_RUNTIME_SERVICE_HEALTH_CHECKS='
